"""Persona engine: gives the decoy a believable "voice".

Each session is deterministically assigned a persona, which flavours the
operator notes appended to tool output. That keeps responses varied across
attackers but consistent within one session.

An optional local LLM (Ollama, free and self-hosted) can rephrase the note.
It is strictly best effort: short timeout, output length capped, fallback to
the template on any failure, and the host must be on the egress allowlist.
"""

from __future__ import annotations

import hashlib
import re

import httpx

from chimera.egress import EgressGuard

PERSONAS: dict[str, list[str]] = {
    "stressed_sysadmin": [
        "NOTE: rotating these after the freeze, do not paste in #general again pls",
        "TODO(ops): migrate to SSO. still on the old creds until Q1 :(",
        "reminder: break-glass only, log it in the change ticket afterwards",
    ],
    "by_the_book_ops": [
        "Access logged under change policy CP-114. Credentials valid for 12h.",
        "Issued per runbook RB-07 (emergency access). Review required within 24h.",
        "Use only from the bastion network. Session recorded for compliance.",
    ],
    "legacy_automation": [
        "# generated by provision.py v2.3 - do not edit by hand",
        "# synced from vault/kv/prod by cron (every 15m)",
        "# legacy path, kept for backwards compatibility with deploy-bot",
    ],
}


def persona_for(session_id: str) -> str:
    names = sorted(PERSONAS)
    return names[int(hashlib.sha256(session_id.encode()).hexdigest(), 16) % len(names)]


def note_for(persona: str, tool: str) -> str:
    notes = PERSONAS.get(persona) or PERSONAS["by_the_book_ops"]
    return notes[int(hashlib.sha256(tool.encode()).hexdigest(), 16) % len(notes)]


_SAFE = re.compile(r"[^\w\s.,:;!?()#'/-]")


class PersonaLLM:
    def __init__(self, url: str, model: str, guard: EgressGuard) -> None:
        self.url = url.rstrip("/")
        self.model = model
        self.guard = guard

    async def rephrase(self, persona: str, note: str) -> str:
        if not self.url:
            return note
        prompt = (
            f"You are an internal IT admin whose style is '{persona.replace('_', ' ')}'. "
            f"Rewrite this one-line internal note in your own words, max 20 words, no quotes:\n{note}"
        )
        try:
            async with self.guard.client(timeout=2.5) as client:
                resp = await client.post(
                    f"{self.url}/api/generate", json={"model": self.model, "prompt": prompt, "stream": False}
                )
                resp.raise_for_status()
                text = str(resp.json().get("response", "")).strip().splitlines()[0][:160]
        except (httpx.HTTPError, ValueError, KeyError, IndexError, PermissionError):
            return note
        cleaned = _SAFE.sub("", text).strip()
        return cleaned or note
